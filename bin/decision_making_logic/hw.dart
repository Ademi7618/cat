import 'dart:io';

void main() {
  int health = 100;
  bool hasKey = false;

  print(''' \n
  ДОБРО ПОЖАЛОВАТЬ В ТЕКСТОВЫЙ КВЕСТ 
  Вы просыпаетесь в темной каменной комнате.
  Перед вами тяжелая деревянная дверь и узкое окно.
  \n
''');

  stdout.write('Куда пойти? (1 - открыть дверь, 2 - выглянуть в окно): ');

  String? choice1 = stdin.readLineSync();

  if (choice1 == '1') {
    print('''\nВы подходите к двери.
    Она заперта на старый ржавый замок.
    Рядом на столе лежит блестящий ключ.
    \n ''');

    stdout.write('Действие? (1 - взять ключ, 2 - попытаться выбить дверь ногой): ');

    String? choice2 = stdin.readLineSync();

    if (choice2 == '1') {
      hasKey = true;

      print('''\n Вы подобрали ключ! 
      Инвентарь обновлен.
      Теперь вы стоите перед запертой сокровищницей в конце коридора.
      \n''');

      stdout.write('Открыть ее? (1 - да, 2 - уйти назад): ');

      String? choice3 = stdin.readLineSync();

      if (choice3 == '1') {
        if (hasKey && health > 50) {
          print('\n[ПОБЕДА!] Вы успешно открыли сокровищницу и забрали артефакт!');
        } else {
          print('\n[ПОРАЖЕНИЕ] Дверь не поддается или у вас слишком мало сил...');
        }
      } else if (choice3 == '2') {
        print('\nВы решили вернуться назад. Игра окончена (ничья).');
      } else {
        print('\nНеверная команда. Стража услышала вас! Конец игры.');
      }

    } else if (choice2 == '2') {
      health -= 60;
      print('''\nВы сильно ударили ногой по двери, но поранили ногу! 
      Здоровье упало до $health HP.
      Шум привлек стражника, который шел по коридору.''');

      stdout.write('Что делать? (1 - драться, 2 - бежать): ');

      String? choiceCombat = stdin.readLineSync();
      if (choiceCombat == '1') {
        print('\n[ПОРАЖЕНИЕ] Без оружия и с низким здоровьем вы проиграли бой.');
      } else {
        print('\n[НИЧЬЯ] Вам удалось скрыться в тенях, но приключение прервано.');
      }

    } else {
      print('\nНеверный ввод. Вы растерялись и проиграли.');
    }

  } else if (choice1 == '2') {
    print('\nВы выглядываете в окно — там огромная высота. Вы сорвались вниз...');
    health = 0;
    print('[ПОРАЖЕНИЕ] Вы погибли. Здоровье: $health HP.');

  } else {
    print('\nНеверная команда! Пожалуйста, выбирайте цифры из предложенных вариантов.');
  }
}